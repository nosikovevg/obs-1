import torch

#Пример 2
# тензоры двумерные, ищем векторное (внешнее) умножение (Outer Product)
A2 = torch.tensor([[1], [4], [3]])
B2 = torch.tensor([[2, 4, 1]]) # Вектор должен быть двумерным!

C2 = A2@B2
# оператор @ вызывает функцию torch.matmul
print(C2)
# результат (С2) - Векторное (внешнее) умножение (Outer Product)
#################
# Скалярное произведение (Dot Product)
# Делаем тензоры плоскими
A1 = torch.tensor([1, 4, 3])  
B1 = torch.tensor([2, 4, 1])  

C1 = A1 @ B1  # Или torch.dot(A, B)
print(C1)   # Результат: tensor(21)  (1*2 + 4*4 + 3*1)
